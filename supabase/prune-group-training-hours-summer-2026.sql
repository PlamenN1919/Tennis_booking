-- ============================================
-- Изчистване на ИЗЛИШНИ ЧАСОВЕ в рамките на летните дати — ПРЕГЛЕДАЙ преди да пуснеш
-- Изпълни в Supabase SQL Editor.
--
-- Контекст: датите вече са само от списъка. Но в някои от тях има групови
-- тренировки в ДРУГИ часове (различни от часа за деня). Този скрипт оставя
-- за всяка дата само реда(овете) с точния начален час от списъка и трие
-- останалите часове.
--
-- Разрешените двойки (дата → начален час) са долу в allowed(...). За всяка
-- дата остават само тренировките с този start_time (по 2 реда — 5–8 г. и
-- 8–11 г.); всичко друго на тази дата пада.
--
-- Обхват: само БЪДЕЩИ дати (>= 12.07.2026), както при предишното изчистване.
-- Миналите 08.07 и 10.07 се оставят непокътнати като история. (Ако искаш да
-- се чистят и те, махни реда `AND gt.date >= DATE '2026-07-12'`.)
--
-- ВНИМАНИЕ: group_training_registrations е с ON DELETE CASCADE — ако някой
-- излишен час има записани деца, те падат с него. Затова първо СТЪПКА 1.
-- Съвпадението е по start_time (часа); end_time не се проверява.
-- ============================================

-- ---------- СТЪПКА 1: PREVIEW — кои часове ще паднат ----------
SELECT
  gt.date,
  gt.start_time,
  gt.end_time,
  gt.age_group,
  COUNT(r.id) FILTER (WHERE r.status = 'confirmed') AS confirmed_registrations
FROM public.group_trainings gt
LEFT JOIN public.group_training_registrations r
  ON r.group_training_id = gt.id
WHERE gt.date >= DATE '2026-07-12'
  AND gt.date IN (
    '2026-07-08','2026-07-10','2026-07-12','2026-07-14','2026-07-19',
    '2026-07-22','2026-07-25','2026-07-28','2026-07-31','2026-08-03',
    '2026-08-07','2026-08-10','2026-08-14','2026-08-18','2026-08-22',
    '2026-08-26','2026-08-30'
  )
  AND NOT EXISTS (
    SELECT 1 FROM (VALUES
      (DATE '2026-07-08', TIME '10:00'),
      (DATE '2026-07-10', TIME '10:00'),
      (DATE '2026-07-12', TIME '10:00'),
      (DATE '2026-07-14', TIME '10:00'),
      (DATE '2026-07-19', TIME '10:00'),
      (DATE '2026-07-22', TIME '17:00'),
      (DATE '2026-07-25', TIME '17:00'),
      (DATE '2026-07-28', TIME '17:00'),
      (DATE '2026-07-31', TIME '17:00'),
      (DATE '2026-08-03', TIME '17:00'),
      (DATE '2026-08-07', TIME '17:00'),
      (DATE '2026-08-10', TIME '17:00'),
      (DATE '2026-08-14', TIME '10:00'),
      (DATE '2026-08-18', TIME '10:00'),
      (DATE '2026-08-22', TIME '17:00'),
      (DATE '2026-08-26', TIME '17:00'),
      (DATE '2026-08-30', TIME '10:00')
    ) AS allowed(d, t)
    WHERE allowed.d = gt.date AND allowed.t = gt.start_time
  )
GROUP BY gt.id, gt.date, gt.start_time, gt.end_time, gt.age_group
ORDER BY gt.date, gt.start_time, gt.age_group;

-- ---------- СТЪПКА 2: DELETE — пусни само след преглед на PREVIEW-а ----------
DELETE FROM public.group_trainings gt
WHERE gt.date >= DATE '2026-07-12'
  AND gt.date IN (
    '2026-07-08','2026-07-10','2026-07-12','2026-07-14','2026-07-19',
    '2026-07-22','2026-07-25','2026-07-28','2026-07-31','2026-08-03',
    '2026-08-07','2026-08-10','2026-08-14','2026-08-18','2026-08-22',
    '2026-08-26','2026-08-30'
  )
  AND NOT EXISTS (
    SELECT 1 FROM (VALUES
      (DATE '2026-07-08', TIME '10:00'),
      (DATE '2026-07-10', TIME '10:00'),
      (DATE '2026-07-12', TIME '10:00'),
      (DATE '2026-07-14', TIME '10:00'),
      (DATE '2026-07-19', TIME '10:00'),
      (DATE '2026-07-22', TIME '17:00'),
      (DATE '2026-07-25', TIME '17:00'),
      (DATE '2026-07-28', TIME '17:00'),
      (DATE '2026-07-31', TIME '17:00'),
      (DATE '2026-08-03', TIME '17:00'),
      (DATE '2026-08-07', TIME '17:00'),
      (DATE '2026-08-10', TIME '17:00'),
      (DATE '2026-08-14', TIME '10:00'),
      (DATE '2026-08-18', TIME '10:00'),
      (DATE '2026-08-22', TIME '17:00'),
      (DATE '2026-08-26', TIME '17:00'),
      (DATE '2026-08-30', TIME '10:00')
    ) AS allowed(d, t)
    WHERE allowed.d = gt.date AND allowed.t = gt.start_time
  );

-- ---------- СТЪПКА 3: Проверка ----------
-- Трябва да върне точно графика от списъка: по 2 реда на бъдеща дата,
-- всичко с правилния начален час (10:00 или 17:00).
SELECT date, start_time, end_time, age_group
FROM public.group_trainings
WHERE date >= DATE '2026-07-12'
  AND date IN (
    '2026-07-12','2026-07-14','2026-07-19','2026-07-22','2026-07-25',
    '2026-07-28','2026-07-31','2026-08-03','2026-08-07','2026-08-10',
    '2026-08-14','2026-08-18','2026-08-22','2026-08-26','2026-08-30'
  )
ORDER BY date, start_time, age_group;
