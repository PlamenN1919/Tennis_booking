-- ============================================
-- Изчистване на групови тренировки ИЗВЪН летния график — ПРЕГЛЕДАЙ преди да пуснеш
-- Изпълни в Supabase SQL Editor.
--
-- Цел: да останат само тренировките от списъка (17-те дати × 2 групи, виж
-- add-group-trainings-summer-2026.sql). Трие само БЪДЕЩИ тренировки
-- (дата >= 12.07.2026), които НЕ са в списъка. Минали записи и техните
-- регистрации се запазват като история (по твое решение).
--
-- ВНИМАНИЕ: group_training_registrations е с ON DELETE CASCADE — изтриването
-- на тренировка трие и записаните за нея деца. Затова първо пусни PREVIEW-а
-- по-долу (СТЪПКА 1) и чак ако си съгласен — DELETE-а (СТЪПКА 2).
-- ============================================

-- ---------- СТЪПКА 1: PREVIEW — какво ще бъде изтрито ----------
-- Показва бъдещите тренировки извън списъка + колко потвърдени регистрации
-- висят на тях (0 = безопасно за триене; >0 = ще загубиш тези записвания).
SELECT
  gt.date,
  gt.start_time,
  gt.end_time,
  gt.age_group,
  gt.is_active,
  COUNT(r.id) FILTER (WHERE r.status = 'confirmed') AS confirmed_registrations
FROM public.group_trainings gt
LEFT JOIN public.group_training_registrations r
  ON r.group_training_id = gt.id
WHERE gt.date >= DATE '2026-07-12'
  AND gt.date NOT IN (
    '2026-07-08','2026-07-10','2026-07-12','2026-07-14','2026-07-19',
    '2026-07-22','2026-07-25','2026-07-28','2026-07-31','2026-08-03',
    '2026-08-07','2026-08-10','2026-08-14','2026-08-18','2026-08-22',
    '2026-08-26','2026-08-30'
  )
GROUP BY gt.id, gt.date, gt.start_time, gt.end_time, gt.age_group, gt.is_active
ORDER BY gt.date, gt.start_time, gt.age_group;

-- ---------- СТЪПКА 2: DELETE — пусни само след преглед на PREVIEW-а ----------
-- (Регистрациите към тези тренировки падат автоматично чрез CASCADE.)
DELETE FROM public.group_trainings
WHERE date >= DATE '2026-07-12'
  AND date NOT IN (
    '2026-07-08','2026-07-10','2026-07-12','2026-07-14','2026-07-19',
    '2026-07-22','2026-07-25','2026-07-28','2026-07-31','2026-08-03',
    '2026-08-07','2026-08-10','2026-08-14','2026-08-18','2026-08-22',
    '2026-08-26','2026-08-30'
  );

-- ---------- СТЪПКА 3: Проверка ----------
-- Трябва да върне 0 реда (няма останали бъдещи тренировки извън списъка).
SELECT date, start_time, age_group
FROM public.group_trainings
WHERE date >= DATE '2026-07-12'
  AND date NOT IN (
    '2026-07-08','2026-07-10','2026-07-12','2026-07-14','2026-07-19',
    '2026-07-22','2026-07-25','2026-07-28','2026-07-31','2026-08-03',
    '2026-08-07','2026-08-10','2026-08-14','2026-08-18','2026-08-22',
    '2026-08-26','2026-08-30'
  )
ORDER BY date, start_time;
